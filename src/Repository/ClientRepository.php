        public function existsByEmail(string $email): bool
    {
        $qb = $this->createQueryBuilder('c');
        $qb->select('count(c.id)')
            ->where('c.email = :email')
            ->setParameter('email', $email);
        $count = (int) $qb->getQuery()->getSingleScalarResult();
        return $count > 0;
    }

